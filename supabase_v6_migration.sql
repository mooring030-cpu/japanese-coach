create table if not exists public.leaderboard (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  display_name text,
  score integer not null default 0,
  total_sessions integer not null default 0,
  learned integer not null default 0,
  streak integer not null default 0,
  attendance_days integer not null default 0,
  first_accuracy numeric(5,2) not null default 0,
  last_study date,
  updated_at timestamptz not null default now()
);
create index if not exists leaderboard_score_idx on public.leaderboard(score desc, updated_at asc);
alter table public.leaderboard enable row level security;
grant select, insert, update on public.leaderboard to authenticated;
drop policy if exists "leaderboard_read_all" on public.leaderboard;
drop policy if exists "leaderboard_write_own" on public.leaderboard;
drop policy if exists "leaderboard_update_own" on public.leaderboard;
create policy "leaderboard_read_all" on public.leaderboard for select to authenticated using (true);
create policy "leaderboard_write_own" on public.leaderboard for insert to authenticated with check ((select auth.uid())=user_id);
create policy "leaderboard_update_own" on public.leaderboard for update to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  timezone text not null default 'Asia/Seoul',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists push_subscriptions_user_idx on public.push_subscriptions(user_id);
alter table public.push_subscriptions enable row level security;
grant select, insert, update, delete on public.push_subscriptions to authenticated;
drop policy if exists "push_own_select" on public.push_subscriptions;
drop policy if exists "push_own_insert" on public.push_subscriptions;
drop policy if exists "push_own_update" on public.push_subscriptions;
drop policy if exists "push_own_delete" on public.push_subscriptions;
create policy "push_own_select" on public.push_subscriptions for select to authenticated using ((select auth.uid())=user_id);
create policy "push_own_insert" on public.push_subscriptions for insert to authenticated with check ((select auth.uid())=user_id);
create policy "push_own_update" on public.push_subscriptions for update to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
create policy "push_own_delete" on public.push_subscriptions for delete to authenticated using ((select auth.uid())=user_id);
